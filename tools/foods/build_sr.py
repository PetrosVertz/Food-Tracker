"""Build the offline selection from the unmodified USDA SR Legacy CSV archive.

Usage: python tools/foods/build_sr.py path/to/FoodData_Central_sr_legacy_food_csv_2018-04.zip
Official download: https://fdc.nal.usda.gov/download-datasets/
Selection rows identify foods by FDC ID and preparation. USDA data are public domain.
"""
import csv
import hashlib
import io
import json
from collections import defaultdict
from pathlib import Path
import sys
import zipfile

HERE = Path(__file__).resolve().parent
ARCHIVE_SHA256 = "b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0"
KEYS = {1008: "kcal", 1003: "protein", 1004: "fat", 1005: "totalCarb", 1079: "fiber",
        1093: "sodium", 1092: "potassium", 2000: "sugar", 1258: "satFat"}
MEASURES = {"cup": "cup", "tablespoon": "tbsp", "tbsp": "tbsp", "teaspoon": "tsp", "tsp": "tsp",
            "cup, chopped": "cupChopped", "cup, sliced": "cupSliced", "cup, slices": "cupSliced",
            "cup, diced": "cupDiced", "cup, cubes": "cupDiced"}
EGG_SIZES = {"small": "smallEgg", "medium": "mediumEgg", "large": "largeEgg"}

def table(archive, name):
    member = next(p for p in archive.namelist() if p.endswith('/' + name + '.csv'))
    with archive.open(member) as source:
        yield from csv.DictReader(io.TextIOWrapper(source, encoding="utf-8-sig"))

def build(path):
    if hashlib.sha256(path.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("The file does not match the selected USDA SR Legacy release")
    with (HERE / "sr-selection.tsv").open(encoding="utf8") as file:
        selection = list(csv.DictReader(file, delimiter='\t'))
    ids = {r["fdc_id"] for r in selection}
    nutrients, portions = defaultdict(dict), defaultdict(dict)
    with zipfile.ZipFile(path) as archive:
        descriptions = {r['fdc_id']: r['description'] for r in table(archive, 'food')}
        for r in table(archive, "food_nutrient"):
            fdc, nutrient = r["fdc_id"], int(r["nutrient_id"])
            if fdc in ids and nutrient in KEYS and r["amount"] != "":
                nutrients[fdc][KEYS[nutrient]] = float(r["amount"])
        for r in table(archive, "food_portion"):
            fdc = r["fdc_id"]
            if fdc not in ids or float(r["amount"] or 0) != 1:
                continue
            modifier = r["modifier"].lower()
            kind = MEASURES.get(modifier)
            if fdc in {"171287", "173424", "172186"}:
                kind = EGG_SIZES.get(modifier, kind)
            if kind and float(r["gram_weight"]) > 0:
                portions[fdc].setdefault(kind, float(r["gram_weight"]))
    records = []
    for row in selection:
        fdc, gid = row["fdc_id"], row["existing_id"]
        assert descriptions[fdc] == row["source_description"], row
        n = nutrients[fdc].copy()
        if set(["kcal", "protein", "fat", "totalCarb", "fiber"]) - n.keys():
            raise ValueError(f"Incomplete macronutrients for {fdc}")
        carbs = n.pop('totalCarb') - n['fiber']
        if carbs < -0.01:
            raise ValueError(f"Carbohydrate inconsistency for {fdc}")
        n['carbs'] = round(max(0, carbs), 2)
        if 'sodium' in n:
            n['salt'] = round(n.pop('sodium') * 2.5 / 1000, 5)
        item = dict(fdc=int(fdc), gid=gid or f'sr_{fdc}', **n)
        if not gid:
            item.update(en=row["english"], el=row["greek"], cat=row["category"], sub=row["subcategory"], state=row["state"], unit='g')
        if portions[fdc]:
            item['measures'] = portions[fdc]
        records.append(item)
    if len({r['gid'] for r in records}) != len(records):
        raise ValueError("Duplicate catalogue ID")
    target = HERE.parents[1] / 'js/data/foods-sr.js'
    lines = [json.dumps(r, ensure_ascii=False, separators=(',', ':')) for r in records]
    target.write_text('// USDA SR Legacy, April 2018. Generated by tools/foods/build_sr.py. Per 100 g edible portion.\nconst SR_FOODS = [\n  ' + ',\n  '.join(lines) + '\n];\n', encoding='utf8')

if __name__ == '__main__':
    build(Path(sys.argv[1]))
