  const ch = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)), lum = c => { const [r, g, b] = c.map(v => { v /= 255; return v <= .03928 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }); return .2126 * r + .7152 * g + .0722 * b; };
